export function normalizeCandidateWord(word: string) {
  return word
    .trim()
    .toLowerCase()
    .replace(/[^a-z'-]/g, "")
    .replace(/^'+|'+$/g, "");
}

export function isExactDictionaryWord(word: string) {
  const normalized = normalizeCandidateWord(word);
  return normalized ? COMMON_WORDS.has(normalized) : false;
}

export function isRealWord(word: string): boolean {
  const normalized = normalizeCandidateWord(word);
  if (!normalized) return false;

  if (normalized === "a" || normalized === "i") return true;
  if (COMMON_WORDS.has(normalized)) return true;

  if (normalized.includes("-")) {
    return normalized.split("-").every((part) => isRealWord(part));
  }

  return false;
}
